-- Line items the caller (Orders/AddOrder.cs, gridView1) wants saved for this PO. Replaces the
-- per-row "INSERT INTO PurchaseOrderDetails VALUES(...)" loop that built the statement by string
-- concatenation and derived SeqNo from a C# counter.
IF TYPE_ID('dbo.tt_PurchaseOrderLines') IS NULL
    CREATE TYPE dbo.tt_PurchaseOrderLines AS TABLE
    (
        ProductCode  varchar(50)    NOT NULL,
        ProductName  varchar(50)    NOT NULL,
        Qty          decimal(18,3)  NOT NULL,
        Units        varchar(50)    NOT NULL,
        Remarks      varchar(250)   NULL,
        SellingPrice decimal(10,2)  NOT NULL
    );
GO
IF OBJECT_ID('dbo.sp_AddSalesOrderRequest') IS NOT NULL
    DROP PROCEDURE dbo.sp_AddSalesOrderRequest;
GO
SET QUOTED_IDENTIFIER ON;
